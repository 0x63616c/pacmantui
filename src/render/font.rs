//! Original 8px bitmap font (6x7 glyphs in an 8x8 cell) + a 3x5 mini digit
//! font for in-maze score popups. All glyph shapes are original designs in
//! the blocky arcade style.
//!
//! Glyph rows are bitmasks with bit 7 = leftmost pixel column.

use super::framebuffer::Frame;

/// Horizontal advance per glyph, pixels.
pub const GLYPH_W: i32 = 8;

#[rustfmt::skip]
const DIGITS: [[u8; 7]; 10] = [
    [0x78, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0x78], // 0
    [0x30, 0x70, 0x30, 0x30, 0x30, 0x30, 0xFC], // 1
    [0x78, 0xCC, 0x0C, 0x38, 0x60, 0xC0, 0xFC], // 2
    [0x78, 0xCC, 0x0C, 0x38, 0x0C, 0xCC, 0x78], // 3
    [0xCC, 0xCC, 0xCC, 0x7C, 0x0C, 0x0C, 0x0C], // 4
    [0xFC, 0xC0, 0xF8, 0x0C, 0x0C, 0xCC, 0x78], // 5
    [0x78, 0xCC, 0xC0, 0xF8, 0xCC, 0xCC, 0x78], // 6
    [0xFC, 0x0C, 0x18, 0x30, 0x60, 0x60, 0x60], // 7
    [0x78, 0xCC, 0xCC, 0x78, 0xCC, 0xCC, 0x78], // 8
    [0x78, 0xCC, 0xCC, 0x7C, 0x0C, 0xCC, 0x78], // 9
];

#[rustfmt::skip]
const LETTERS: [[u8; 7]; 26] = [
    [0x78, 0xCC, 0xCC, 0xFC, 0xCC, 0xCC, 0xCC], // A
    [0xF8, 0xCC, 0xCC, 0xF8, 0xCC, 0xCC, 0xF8], // B
    [0x78, 0xCC, 0xC0, 0xC0, 0xC0, 0xCC, 0x78], // C
    [0xF8, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0xF8], // D
    [0xFC, 0xC0, 0xC0, 0xF8, 0xC0, 0xC0, 0xFC], // E
    [0xFC, 0xC0, 0xC0, 0xF8, 0xC0, 0xC0, 0xC0], // F
    [0x78, 0xCC, 0xC0, 0xDC, 0xCC, 0xCC, 0x78], // G
    [0xCC, 0xCC, 0xCC, 0xFC, 0xCC, 0xCC, 0xCC], // H
    [0x78, 0x30, 0x30, 0x30, 0x30, 0x30, 0x78], // I
    [0x3C, 0x0C, 0x0C, 0x0C, 0x0C, 0xCC, 0x78], // J
    [0xCC, 0xD8, 0xF0, 0xE0, 0xF0, 0xD8, 0xCC], // K
    [0xC0, 0xC0, 0xC0, 0xC0, 0xC0, 0xC0, 0xFC], // L
    [0xCC, 0xFC, 0xFC, 0xCC, 0xCC, 0xCC, 0xCC], // M
    [0xCC, 0xEC, 0xFC, 0xDC, 0xCC, 0xCC, 0xCC], // N
    [0x78, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0x78], // O
    [0xF8, 0xCC, 0xCC, 0xF8, 0xC0, 0xC0, 0xC0], // P
    [0x78, 0xCC, 0xCC, 0xCC, 0xDC, 0x78, 0x0C], // Q
    [0xF8, 0xCC, 0xCC, 0xF8, 0xF0, 0xD8, 0xCC], // R
    [0x78, 0xCC, 0xC0, 0x78, 0x0C, 0xCC, 0x78], // S
    [0xFC, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30], // T
    [0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0x78], // U
    [0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0x78, 0x30], // V
    [0xCC, 0xCC, 0xCC, 0xCC, 0xFC, 0xFC, 0xCC], // W
    [0xCC, 0xCC, 0x78, 0x30, 0x78, 0xCC, 0xCC], // X
    [0xCC, 0xCC, 0x78, 0x30, 0x30, 0x30, 0x30], // Y
    [0xFC, 0x0C, 0x18, 0x30, 0x60, 0xC0, 0xFC], // Z
];

const BLANK: [u8; 7] = [0; 7];

/// Glyph bitmap for a character (case-insensitive; unknown -> blank).
pub fn glyph(c: char) -> [u8; 7] {
    let c = c.to_ascii_uppercase();
    match c {
        '0'..='9' => DIGITS[(c as usize) - ('0' as usize)],
        'A'..='Z' => LETTERS[(c as usize) - ('A' as usize)],
        '!' => [0x30, 0x30, 0x30, 0x30, 0x30, 0x00, 0x30],
        '-' => [0x00, 0x00, 0x00, 0xFC, 0x00, 0x00, 0x00],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x30, 0x30],
        ',' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x30, 0x60],
        ':' => [0x00, 0x30, 0x30, 0x00, 0x30, 0x30, 0x00],
        '/' => [0x0C, 0x18, 0x18, 0x30, 0x60, 0x60, 0xC0],
        '>' => [0xC0, 0x60, 0x30, 0x18, 0x30, 0x60, 0xC0],
        '<' => [0x0C, 0x18, 0x30, 0x60, 0x30, 0x18, 0x0C],
        '?' => [0x78, 0xCC, 0x0C, 0x18, 0x30, 0x00, 0x30],
        '\'' => [0x30, 0x30, 0x60, 0x00, 0x00, 0x00, 0x00],
        '"' => [0x6C, 0x6C, 0x00, 0x00, 0x00, 0x00, 0x00],
        _ => BLANK,
    }
}

/// Pixel width of `text` at scale 1.
pub fn text_width(text: &str) -> i32 {
    text.chars().count() as i32 * GLYPH_W
}

pub fn draw_text(fb: &mut Frame, x: i32, y: i32, text: &str, rgb: [u8; 3]) {
    draw_text_scaled(fb, x, y, text, rgb, 1);
}

/// Draw text with each font pixel expanded to a k x k block.
pub fn draw_text_scaled(fb: &mut Frame, x: i32, y: i32, text: &str, rgb: [u8; 3], k: i32) {
    let mut cx = x;
    for c in text.chars() {
        let g = glyph(c);
        for (ry, row) in g.iter().enumerate() {
            for bit in 0..8 {
                if row & (0x80 >> bit) != 0 {
                    fb.fill_rect(cx + bit * k, y + ry as i32 * k, k, k, rgb);
                }
            }
        }
        cx += GLYPH_W * k;
    }
}

// --- mini 3x5 digit font (score popups) ------------------------------------

#[rustfmt::skip]
const MINI_DIGITS: [[u8; 5]; 10] = [
    [0b111, 0b101, 0b101, 0b101, 0b111], // 0
    [0b010, 0b110, 0b010, 0b010, 0b111], // 1
    [0b111, 0b001, 0b111, 0b100, 0b111], // 2
    [0b111, 0b001, 0b111, 0b001, 0b111], // 3
    [0b101, 0b101, 0b111, 0b001, 0b001], // 4
    [0b111, 0b100, 0b111, 0b001, 0b111], // 5
    [0b111, 0b100, 0b111, 0b101, 0b111], // 6
    [0b111, 0b001, 0b001, 0b010, 0b010], // 7
    [0b111, 0b101, 0b111, 0b101, 0b111], // 8
    [0b111, 0b101, 0b111, 0b001, 0b111], // 9
];

/// Pixel width of `value` in the mini font (3px digits, 1px gaps).
pub fn mini_number_width(value: u32) -> i32 {
    let digits = value.to_string().len() as i32;
    digits * 4 - 1
}

/// Draw `value` centered on (cx, cy) in the 3x5 mini font.
pub fn draw_mini_number(fb: &mut Frame, cx: i32, cy: i32, value: u32, rgb: [u8; 3]) {
    let s = value.to_string();
    let mut x = cx - mini_number_width(value) / 2;
    let y = cy - 2;
    for c in s.chars() {
        let d = (c as usize) - ('0' as usize);
        let g = &MINI_DIGITS[d];
        for (ry, row) in g.iter().enumerate() {
            for bit in 0..3 {
                if row & (0b100 >> bit) != 0 {
                    fb.put(x + bit, y + ry as i32, rgb);
                }
            }
        }
        x += 4;
    }
}
